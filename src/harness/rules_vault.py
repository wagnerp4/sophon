"""Compile agent rules from the Obsidian vault into a repo's AGENTS.md.

The vault (default ``~/Linux-PC/Agents``) holds two layers of notes:

- across-repo: ``Global/**`` notes with ``layer: global``
- repo: ``Projects/<name>/**`` notes with ``layer: project`` and ``project: <name>``

Only notes whose frontmatter has ``agents: export`` are compiled. A repo is matched to
its project through the ``repo:`` field of ``Projects/<name>/project.md``.
"""

from __future__ import annotations

import os
import re
from dataclasses import dataclass
from pathlib import Path

import yaml

DEFAULT_VAULT = "~/Linux-PC/Agents"
VAULT_ENV = "SOPHON_AGENT_VAULT"
GENERATED_MARKER = "<!-- generated by sophon-cli rules sync"
CLAUDE_MD_CONTENT = "@AGENTS.md\n"

_FRONTMATTER = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n?", re.DOTALL)
_COMMENT = re.compile(r"%%.*?%%", re.DOTALL)
_WIKILINK = re.compile(r"!?\[\[([^\]|#]*)(?:#[^\]|]*)?(?:\|([^\]]*))?\]\]")
_HEADING = re.compile(r"^(#{1,6})(\s)")
_FENCE = re.compile(r"^\s*(```|~~~)")


class RulesError(Exception):
    """Raised for a missing vault, unknown project, or a hand-written AGENTS.md."""


@dataclass(frozen=True)
class RuleNote:
    path: Path
    rel: str
    layer: str
    project: str
    order: int
    title: str
    body: str
    language: str = ""


@dataclass(frozen=True)
class Project:
    name: str
    repo: Path
    note: Path
    languages: tuple[str, ...] | None = None

    def wants(self, note: RuleNote) -> bool:
        """Whether ``note`` belongs in this project's compiled rules."""
        if note.layer == "project":
            return note.project == self.name
        if note.language and self.languages is not None:
            return note.language in self.languages
        return True


def vault_root(explicit: str | Path | None = None) -> Path:
    raw = (
        str(explicit)
        if explicit
        else os.environ.get(VAULT_ENV, "").strip() or DEFAULT_VAULT
    )
    root = Path(raw).expanduser()
    if not root.is_dir():
        raise RulesError(
            f"agent vault not found: {root} (set {VAULT_ENV} or pass --vault)"
        )
    return root


def split_frontmatter(text: str) -> tuple[dict, str]:
    match = _FRONTMATTER.match(text)
    if not match:
        return {}, text
    try:
        meta = yaml.safe_load(match.group(1)) or {}
    except yaml.YAMLError:
        return {}, text
    if not isinstance(meta, dict):
        meta = {}
    return meta, text[match.end() :]


def _resolve_wikilink(match: re.Match[str]) -> str:
    target, alias = match.group(1), match.group(2)
    if alias:
        return alias.strip()
    return target.strip().rsplit("/", 1)[-1]


def clean_body(body: str, shift: int) -> tuple[str, str]:
    """Return (title, body) with comments stripped, links flattened, headings shifted.

    The first H1 becomes the title and is removed from the body.
    """
    body = _COMMENT.sub("", body)
    title = ""
    out: list[str] = []
    in_fence = False
    for line in body.splitlines():
        if _FENCE.match(line):
            in_fence = not in_fence
            out.append(line)
            continue
        if in_fence:
            out.append(line)
            continue
        line = _WIKILINK.sub(_resolve_wikilink, line)
        heading = _HEADING.match(line)
        if heading:
            level = len(heading.group(1))
            if level == 1 and not title:
                title = line[heading.end() :].strip()
                continue
            line = "#" * min(6, level + shift) + line[len(heading.group(1)) :]
        out.append(line)
    text = "\n".join(out).strip("\n")
    text = re.sub(r"\n{3,}", "\n\n", text)
    return title, text


def load_notes(root: Path) -> list[RuleNote]:
    notes: list[RuleNote] = []
    for path in sorted(root.rglob("*.md")):
        if any(part.startswith(".") for part in path.relative_to(root).parts):
            continue
        meta, body = split_frontmatter(path.read_text(encoding="utf-8"))
        if str(meta.get("agents", "")).strip().lower() != "export":
            continue
        layer = str(meta.get("layer", "")).strip().lower()
        if layer not in ("global", "project"):
            continue
        title, text = clean_body(body, shift=2)
        try:
            order = int(meta.get("order", 100))
        except (TypeError, ValueError):
            order = 100
        notes.append(
            RuleNote(
                path=path,
                rel=path.relative_to(root).as_posix(),
                layer=layer,
                project=str(meta.get("project", "") or "").strip(),
                order=order,
                title=str(meta.get("title") or title or path.stem),
                body=text,
                language=str(meta.get("language", "") or "").strip().lower(),
            )
        )
    notes.sort(key=lambda n: (n.order, n.rel))
    return notes


def list_projects(root: Path) -> list[Project]:
    projects: list[Project] = []
    for note in sorted((root / "Projects").glob("*/project.md")):
        meta, _ = split_frontmatter(note.read_text(encoding="utf-8"))
        repo = str(meta.get("repo", "") or "").strip()
        name = str(meta.get("project", "") or note.parent.name).strip()
        langs = meta.get("languages")
        languages = (
            tuple(str(lang).strip().lower() for lang in langs)
            if isinstance(langs, list)
            else None
        )
        if repo:
            projects.append(Project(name, Path(repo).expanduser(), note, languages))
    return projects


def find_project(root: Path, repo: Path, name: str | None = None) -> Project:
    projects = list_projects(root)
    if name:
        for project in projects:
            if project.name == name:
                return project
        raise RulesError(f"no project named {name!r} in {root / 'Projects'}")
    target = repo.resolve()
    for project in projects:
        if project.repo.resolve() == target:
            return project
    known = ", ".join(f"{p.name} -> {p.repo}" for p in projects) or "none"
    raise RulesError(f"no vault project maps to {target} (known: {known})")


def render_agents_md(root: Path, project: Project) -> str:
    notes = [n for n in load_notes(root) if project.wants(n)]
    repo_notes = [n for n in notes if n.layer == "project"]
    global_notes = [n for n in notes if n.layer == "global"]
    lines = [
        f"{GENERATED_MARKER} from the Obsidian agent vault. Do not edit by hand:",
        "     change the vault notes listed under Sources, then run `sophon-cli rules sync`. -->",
        "",
        f"# AGENTS.md ({project.name})",
        "",
        "Rules for every coding agent working in this repo. Two layers: the repo layer, then the",
        "across-repo layer. On conflict the repo layer wins, and an explicit human instruction",
        "beats both.",
    ]
    for heading, group in (
        (f"Repo layer: {project.name}", repo_notes),
        ("Across-repo layer", global_notes),
    ):
        lines += ["", f"## {heading}"]
        for note in group:
            lines += ["", f"### {note.title}"]
            if note.body:
                lines += ["", note.body]
    lines += ["", "## Sources", ""]
    lines += [f"- `{n.rel}`" for n in repo_notes + global_notes]
    return "\n".join(lines) + "\n"


@dataclass(frozen=True)
class SyncResult:
    project: Project
    agents_path: Path
    changed: bool
    claude_created: bool
    content: str


def sync(
    repo: Path,
    vault: str | Path | None = None,
    *,
    project_name: str | None = None,
    check: bool = False,
    force: bool = False,
) -> SyncResult:
    root = vault_root(vault)
    project = find_project(root, repo, project_name)
    content = render_agents_md(root, project)
    agents_path = repo / "AGENTS.md"
    current = agents_path.read_text(encoding="utf-8") if agents_path.exists() else None
    changed = current != content
    if current is not None and GENERATED_MARKER not in current and not force:
        raise RulesError(
            f"{agents_path} is hand-written; move its rules into the vault or pass --force"
        )
    claude_path = repo / "CLAUDE.md"
    claude_created = False
    if not check:
        if changed:
            agents_path.write_text(content, encoding="utf-8")
        if not claude_path.exists():
            claude_path.write_text(CLAUDE_MD_CONTENT, encoding="utf-8")
            claude_created = True
    return SyncResult(project, agents_path, changed, claude_created, content)
